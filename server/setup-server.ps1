foreach ($verb in @('-Status', '-Check', '-Uninstall')) {
    Write-Host ('  powershell -ExecutionPolicy Bypass -File "' + $ScriptPath + '" ' + $verb + ' ' + $CommonArgs)
}
if (-not $healthy) { Write-Log ERROR 'self-test failed'; exit 1 }
Write-Log INFO 'setup complete'
