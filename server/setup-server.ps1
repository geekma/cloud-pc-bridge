# ---- small helpers -----------------------------------------------------------
function Write-Log {
    param([string]$Level = 'INFO', [string]$Message)
    $line = '{0} [{1}] {2}' -f (Get-Date).ToString('yyyy-MM-dd HH:mm:ss'), $Level, ($Message -replace '[\r\n]+', ' ')
    $locked = $false
    try { $locked = $script:BridgeMutex.WaitOne(3000) } catch { }
    try {
        # Rotate by copying and truncating IN PLACE. Replacing the file while
        # another process holds an append handle creates sparse NUL gaps.
        if ((Test-Path -LiteralPath $LogPath) -and (Get-Item -LiteralPath $LogPath).Length -gt 1048576) {
            Copy-Item -LiteralPath $LogPath -Destination ($LogPath + '.1') -Force
            [System.IO.File]::WriteAllText($LogPath, '', (New-Object System.Text.UTF8Encoding($false)))
        }
        [System.IO.File]::AppendAllText($LogPath, $line + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
    } catch { }
    finally { if ($locked) { try { $script:BridgeMutex.ReleaseMutex() } catch { } } }
    if (-not $Check) { Write-Host $line }
}

function Write-Text {
    param([string]$Path, [string]$Text)
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($false)))
}

function Write-ScriptFile {
    param([string]$Path, [string]$Text)
    # Windows PowerShell 5.1 needs a UTF-8 BOM to read non-ASCII .ps1 correctly.
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($true)))
}

function New-Token {
    $bytes = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RNGCryptoServiceProvider]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    return (-join ($bytes | ForEach-Object { $_.ToString('x2') }))
}

function Set-Property {
    param($Object, [string]$Name, $Value)
    if ($Object.PSObject.Properties[$Name]) { $Object.$Name = $Value }
    else { Add-Member -InputObject $Object -NotePropertyName $Name -NotePropertyValue $Value -Force }
}

function Get-BridgeConfig {
    if (-not (Test-Path -LiteralPath $ConfigPath)) { return $null }
    try { return (Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json) } catch { return $null }
}

function Find-Node {
    if ($NodeExe -and (Test-Path -LiteralPath $NodeExe)) { return (Resolve-Path -LiteralPath $NodeExe).Path }
    $cmd = Get-Command node.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $candidates = @()
    if ($env:ProgramFiles) { $candidates += (Join-Path $env:ProgramFiles 'nodejs\node.exe') }
    $pf86 = ${env:ProgramFiles(x86)}
    if ($pf86) { $candidates += (Join-Path $pf86 'nodejs\node.exe') }
    if ($env:LOCALAPPDATA) { $candidates += (Join-Path $env:LOCALAPPDATA 'Programs\nodejs\node.exe') }
    foreach ($p in $candidates) { if (Test-Path -LiteralPath $p) { return $p } }
    throw 'Node.js 18+ not found. Install it first, or pass -NodeExe <full path to node.exe>.'
}

function Set-RestrictedAcl {
    param([string]$Path)
    $sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    # icacls needs a leading '*' when the grantee is a raw SID (not a name).
    try {
        & icacls.exe $Path /inheritance:r /grant:r "*S-1-5-32-544:F" "*S-1-5-18:F" "*${sid}:F" 2>&1 | Out-Null
    } catch { Write-Log WARN ('ACL tighten failed for ' + $Path) }
}

function New-DefaultConfig {
    param([string]$Tok, [bool]$Exec)
    $ps64 = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $ps32 = Join-Path $env:WINDIR 'SysWOW64\WindowsPowerShell\v1.0\powershell.exe'
    $cmde = Join-Path $env:WINDIR 'System32\cmd.exe'
    $shells = [ordered]@{}
    $shells['powershell'] = [ordered]@{
        exe = $ps64
        prefix = '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; '
        args = @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', '{cmd}')
        encoding = 'utf8'
    }
    $shells['ps32'] = [ordered]@{
        exe = $ps32
        prefix = '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; '
        args = @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', '{cmd}')
        encoding = 'utf8'
    }
    $shells['cmd'] = [ordered]@{ exe = $cmde; args = @('/d', '/s', '/c', '{cmd}'); encoding = 'gbk' }
    return [ordered]@{
        token = $Tok
        port = $Port
        proxyPort = $ProxyPort
        proxyHost = ''
        home = $BridgeDir
        roots = [ordered]@{ data = $DataDir; logs = $LogDir; bridge = $BridgeDir }
        denyWrite = @('\.(mdb|ldb|sqlite|bak)$', '[\\/](\.git|\.svn|node_modules)[\\/]')
        denyRead = @('[\\/]config\.json$', '\.(key|pem|pfx|p12)$', '[\\/]id_rsa', '[\\/]\.ssh[\\/]')
        rateLimitPerMinute = 180
        maxBodyBytes = 5242880
        execEnabled = $Exec
        execHardMaxMs = 600000
        execMaxMs = 60000
        execMaxCommand = 8000
        execMaxOut = 65536
        execMaxErr = 16384
        execMaxConcurrent = 3
        execDeny = @(
            '\bformat\s+[a-z]:', '\bdiskpart\b', '\bbcdedit\b',
            '\brm\s+-rf\s+/', '\bmkfs\b', '\bdd\s+if=',
            '\b(Stop-Computer|Restart-Computer|shutdown\.exe|reboot)\b',
            '\bnet\s+user\b[^\r\n]*/add', '\bSet-ExecutionPolicy\b'
        )
        execAllow = @()
        defaultShell = 'powershell'
        oemEncoding = 'gbk'
        shells = $shells
    }
}

# ---- HTTP probes -------------------------------------------------------------
function Test-Health {
    param($Cfg, [int]$Timeout = 5)
    try {
        $uri = 'http://127.0.0.1:' + $Cfg.port + '/__agent/health'
        $headers = @{ Authorization = 'Bearer ' + $Cfg.token }
        $r = Invoke-WebRequest -Uri $uri -Method Post -Headers $headers `
             -ContentType 'application/json' -Body '{}' -UseBasicParsing -TimeoutSec $Timeout
        if ($r.StatusCode -ne 200) { return $false }
        return [bool](($r.Content | ConvertFrom-Json).ok)
    } catch { return $false }
}

function Test-NoAuthRejected {
    param($Cfg)
    try {
        $uri = 'http://127.0.0.1:' + $Cfg.port + '/__agent/health'
        $r = Invoke-WebRequest -Uri $uri -Method Post -ContentType 'application/json' `
             -Body '{}' -UseBasicParsing -TimeoutSec 5
        return ($r.StatusCode -eq 401)
    } catch {
        $resp = $_.Exception.Response
        return ($resp -and ([int]$resp.StatusCode -eq 401))
    }
}

function Resolve-TunnelUrl {
    if ($TunnelUrl) { return $TunnelUrl.TrimEnd('/') }
    # Only auto-detect when THIS script owns a tunnel, and only accept a tunnel
    # that forwards to OUR port. Picking an unrelated tunnel would put a wrong
    # URL into the handoff file.
    if (-not $TunnelCommand) { return '' }
    try {
        $r = Invoke-RestMethod -Uri 'http://127.0.0.1:4040/api/tunnels' -TimeoutSec 3
        $want = ':' + $script:Cfg.port + '$'
        foreach ($t in @($r.tunnels)) {
            $addr = [string]$t.config.addr
            if ($t.public_url -like 'https://*' -and $addr -match $want) { return $t.public_url }
        }
    } catch { }
    return ''
}

# ---- install files -----------------------------------------------------------
function Install-Files {
    $null = New-Item -ItemType Directory -Force -Path $BridgeDir, $DataDir, $LogDir
    [System.IO.File]::WriteAllBytes($GatewayPath, [Convert]::FromBase64String(($GatewayB64 -replace '\s', '')))
    Write-Log INFO ('wrote ' + $GatewayPath)

    $existing = Get-BridgeConfig
    $tok = $Token.Trim()
    if ($RotateToken -or -not $tok) {
        if ($existing -and $existing.token -and -not $RotateToken -and $existing.token -notlike '*<*') {
            $tok = [string]$existing.token
        } else {
            $tok = New-Token
        }
    }
    if ($tok.Length -lt 32 -or $tok -match '\s') {
        throw '-Token must be at least 32 characters with no whitespace (64 hex chars recommended).'
    }

    $exec = $false
    if ($EnableExec) { $exec = $true }
    if ($DisableExec) { $exec = $false }
    if ($existing -and -not $EnableExec -and -not $DisableExec) { $exec = [bool]$existing.execEnabled }

    if ($existing) {
        $cfg = $existing
        Set-Property $cfg 'token' $tok
        Set-Property $cfg 'port' $Port
        Set-Property $cfg 'proxyPort' $ProxyPort
        Set-Property $cfg 'home' $BridgeDir
        Set-Property $cfg 'execEnabled' $exec
        Set-Property $cfg 'roots' ([ordered]@{ data = $DataDir; logs = $LogDir; bridge = $BridgeDir })
    } else {
        $cfg = New-DefaultConfig -Tok $tok -Exec $exec
    }
    Write-Text -Path $ConfigPath -Text ($cfg | ConvertTo-Json -Depth 12)
    $script:Cfg = Get-BridgeConfig
    Set-RestrictedAcl -Path $ConfigPath

    $node = Find-Node
    $check = & $node --check $GatewayPath 2>&1
    if ($LASTEXITCODE -ne 0) { throw ('node --check failed: ' + ($check -join ' ')) }
    Write-Log INFO ('node syntax OK, execEnabled=' + $script:Cfg.execEnabled)

    if ($KeepAlive -or (Test-Path -LiteralPath $KeepAlivePath)) {
        [System.IO.File]::WriteAllBytes($KeepAlivePath, [Convert]::FromBase64String(($KeepAliveB64 -replace '\s', '')))
        Write-Log INFO ('wrote ' + $KeepAlivePath)
    }
}

# ---- scheduled tasks ---------------------------------------------------------
function Register-Jobs {
    $node = Find-Node
    $psExe = Join-Path $PSHOME 'powershell.exe'
    $user = "$env:USERDOMAIN\$env:USERNAME"
    $principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
    $atLogon = New-ScheduledTaskTrigger -AtLogOn -User $user
    $every5 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(-5) `
                  -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)
    $every1 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(-2) `
                  -RepetitionInterval (New-TimeSpan -Minutes 1) -RepetitionDuration (New-TimeSpan -Days 3650)
    $longRunning = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew `
                  -ExecutionTimeLimit ([TimeSpan]::Zero) -StartWhenAvailable `
                  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -Hidden
    $shortRunning = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew `
                  -ExecutionTimeLimit (New-TimeSpan -Minutes 5) -StartWhenAvailable `
                  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -Hidden

    # 1) Gateway: at logon AND every 5 minutes. IgnoreNew means the repetition
    #    only does something when the previous instance died => process self-heal.
    $a1 = New-ScheduledTaskAction -Execute $node -Argument ('"{0}"' -f $GatewayPath)
    Register-ScheduledTask -TaskName $TaskGateway -Action $a1 -Trigger @($atLogon, $every5) `
        -Principal $principal -Settings $longRunning -Description 'Remote bridge gateway (loopback only)' -Force | Out-Null

    # 2) Watchdog: every minute POSTs health and restarts gateway / tunnel.
    $a2 = New-ScheduledTaskAction -Execute $psExe -Argument ('-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -Check {1}' -f $ScriptPath, $CommonArgs)
    Register-ScheduledTask -TaskName $TaskWatchdog -Action $a2 -Trigger @($atLogon, $every1) `
        -Principal $principal -Settings $shortRunning -Description 'Remote bridge health watchdog' -Force | Out-Null

    # 3) Tunnel (optional): a .ps1 file avoids all quoting problems.
    if ($TunnelCommand) {
        Write-ScriptFile -Path $TunnelCmdPath -Text ($TunnelCommand + "`r`n")
        $a3 = New-ScheduledTaskAction -Execute $psExe -Argument ('-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}"' -f $TunnelCmdPath)
        Register-ScheduledTask -TaskName $TaskTunnel -Action $a3 -Trigger @($atLogon, $every5) `
            -Principal $principal -Settings $longRunning -Description 'Public tunnel for remote bridge' -Force | Out-Null
        $tunnelCfg = [ordered]@{ command = $TunnelCommand; url = $TunnelUrl; task = $TaskTunnel }
        Write-Text -Path $TunnelCfgPath -Text ($tunnelCfg | ConvertTo-Json -Depth 5)
    }

    # 4) Session keepalive (optional, see keepalive.ps1 header for its limits).
    if ($KeepAlive) {
        $a4 = New-ScheduledTaskAction -Execute $psExe -Argument ('-Sta -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -Run -StateDir "{1}"' -f $KeepAlivePath, $BridgeDir)
        Register-ScheduledTask -TaskName $TaskKeepAlive -Action $a4 -Trigger @($atLogon, $every1) `
            -Principal $principal -Settings $longRunning -Description 'Session-level keepalive (optional)' -Force | Out-Null
    }
    Write-Log INFO 'scheduled tasks registered'

    foreach ($name in @($TaskGateway, $TaskTunnel, $TaskKeepAlive, $TaskWatchdog)) {
        if (Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue) {
            try { Start-ScheduledTask -TaskName $name -ErrorAction Stop } catch { Write-Log WARN ('start task failed: ' + $name) }
        }
    }
}

# ---- watchdog action ---------------------------------------------------------
function Get-CheckState {
    if (Test-Path -LiteralPath $CheckStatePath) {
        try { return (Get-Content -LiteralPath $CheckStatePath -Raw | ConvertFrom-Json) } catch { }
    }
    return [pscustomobject]@{ LastHeartbeatLog = 0; LastTunnelRestart = 0 }
}
function Save-CheckState($s) {
    $locked = $false
    try { $locked = $script:BridgeMutex.WaitOne(3000) } catch { }
    try { Write-Text -Path $CheckStatePath -Text ($s | ConvertTo-Json -Depth 5) }
    finally { if ($locked) { try { $script:BridgeMutex.ReleaseMutex() } catch { } } }
}

function Invoke-Check {
    $cfg = Get-BridgeConfig
    if (-not $cfg) { Write-Log ERROR 'config.json missing; run setup again'; return }
    $state = Get-CheckState
    $now = (Get-Date).Ticks

    if (-not (Test-Health -Cfg $cfg)) {
        Write-Log WARN 'health failed -> restarting gateway task'
        try {
            Stop-ScheduledTask -TaskName $TaskGateway -ErrorAction SilentlyContinue
            Start-ScheduledTask -TaskName $TaskGateway -ErrorAction Stop
        } catch {
            try { Start-Process -FilePath (Find-Node) -ArgumentList ('"{0}"' -f $GatewayPath) -WindowStyle Hidden | Out-Null } catch { }
        }
    } elseif (($now - $state.LastHeartbeatLog) -gt (New-TimeSpan -Minutes 10).Ticks) {
        Write-Log INFO 'healthy'
        $state.LastHeartbeatLog = $now
        Save-CheckState $state
    }

    if (Test-Path -LiteralPath $TunnelCfgPath) {
        $t = Get-Content -LiteralPath $TunnelCfgPath -Raw | ConvertFrom-Json
        if ($t.url) {
            $publicOk = $false
            try {
                $uri = ([string]$t.url).TrimEnd('/') + '/__agent/health'
                $headers = @{ Authorization = 'Bearer ' + $cfg.token }
                if ($uri -like '*ngrok*') { $headers['ngrok-skip-browser-warning'] = 'true' }
                $r = Invoke-WebRequest -Uri $uri -Method Post -Headers $headers `
                     -ContentType 'application/json' -Body '{}' -UseBasicParsing -TimeoutSec 8
                $publicOk = ($r.StatusCode -eq 200 -and [bool](($r.Content | ConvertFrom-Json).ok))
            } catch { }
            if (-not $publicOk -and ($now - $state.LastTunnelRestart) -gt (New-TimeSpan -Seconds 60).Ticks) {
                Write-Log WARN 'public URL unhealthy -> restarting tunnel task'
                try {
                    Stop-ScheduledTask -TaskName $TaskTunnel -ErrorAction SilentlyContinue
                    Start-ScheduledTask -TaskName $TaskTunnel -ErrorAction Stop
                } catch { Write-Log WARN 'tunnel task restart failed' }
                $state.LastTunnelRestart = $now
                Save-CheckState $state
            }
        }
    }
}

# ---- status / uninstall ------------------------------------------------------
function Show-Status {
    $cfg = Get-BridgeConfig
    foreach ($name in @($TaskGateway, $TaskWatchdog, $TaskTunnel, $TaskKeepAlive)) {
        $t = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
        if ($t) {
            $i = Get-ScheduledTaskInfo -TaskName $name
            Write-Host ('{0,-28} {1,-8} last={2} result={3}' -f $name, $t.State, $i.LastRunTime, $i.LastTaskResult)
        }
    }
    if ($cfg) {
        Write-Host ('local health  : ' + $(if (Test-Health -Cfg $cfg) { 'OK' } else { 'FAIL' }))
        Write-Host ('no-token 401  : ' + $(if (Test-NoAuthRejected -Cfg $cfg) { 'OK' } else { 'FAIL' }))
        Write-Host ('execEnabled   : ' + $cfg.execEnabled)
        Write-Host ('port          : ' + $cfg.port)
    }
    if (Test-Path -LiteralPath $TunnelCfgPath) {
        $t = Get-Content -LiteralPath $TunnelCfgPath -Raw | ConvertFrom-Json
        Write-Host ('tunnel url    : ' + $t.url)
    }
    if (Test-Path -LiteralPath $LogPath) { Get-Content -LiteralPath $LogPath -Tail 12 | ForEach-Object { Write-Host ('  ' + $_) } }
}

function Invoke-Uninstall {
    foreach ($name in @($TaskGateway, $TaskWatchdog, $TaskTunnel, $TaskKeepAlive)) {
        $t = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
        if ($t) {
            try { Stop-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue } catch { }
            try { Unregister-ScheduledTask -TaskName $name -Confirm:$false -ErrorAction Stop } catch { }
            Write-Host ('removed task: ' + $name)
        }
    }
    Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" -ErrorAction SilentlyContinue |
        Where-Object { $_.CommandLine -like ('*' + $GatewayPath + '*') } |
        ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
    Write-Host 'Generated files are KEPT on purpose (they contain your data and token):'
    foreach ($p in @($GatewayPath, $ConfigPath, $HandoffPath, $TunnelCfgPath, $KeepAlivePath)) {
        if (Test-Path -LiteralPath $p) { Write-Host ('  ' + $p) }
    }
    Write-Host 'Delete them manually only when you are sure you no longer need this bridge.'
}

# ---- main --------------------------------------------------------------------
